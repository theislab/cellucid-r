# Writes the R side of the viewer's action catalog from
# inst/action_catalog.json (the web app's scripts/generate-action-catalog.mjs
# writes that file, byte for byte its tests/fixtures/action-catalog.json):
#
# - R/actions-generated.R: one exported function per action,
#   cellucid_<tool>(viewer, <params>), each sending its action with
#   .act() (R/actions.R) and returning the request;
# - man/cellucid_<tool>.Rd: its help page, from the action's title, summary,
#   parameter schemas and result schema;
# - the block of NAMESPACE between the GENERATED ACTION EXPORTS markers;
# - the contents of _pkgdown.yml's reference group "The viewer's actions".
#
# Run from the package root after the catalog changes:
#
#   Rscript tools/generate-actions.R
#
# tests/testthat/test-actions.R renders the same files in memory
# (render_actions()) and fails while a file on disk differs from them, a page
# is left over from an action the catalog no longer has, or a generated name
# takes a hand-written export's. Needs jsonlite only, never the package itself.

generated_header <- c(
  "Generated by tools/generate-actions.R from inst/action_catalog.json: do not",
  "edit. Run `Rscript tools/generate-actions.R` from the package root after the",
  "catalog changes; tests/testthat/test-actions.R fails while this file is stale."
)
# The first line of every generated help page: what tells one from a
# hand-written page.
generated_rd_marker <- paste0("% ", generated_header[[1L]])
namespace_begin <- "# BEGIN GENERATED ACTION EXPORTS (tools/generate-actions.R; do not edit this block)"
namespace_end <- "# END GENERATED ACTION EXPORTS"
pkgdown_actions_title <- "  - title: The viewer's actions"

reserved_words <- c(
  "if", "else", "repeat", "while", "function", "for", "next", "break", "TRUE", "FALSE", "NULL", "Inf", "NaN",
  "NA", "NA_integer_", "NA_real_", "NA_complex_", "NA_character_", "in"
)

# The R argument of a parameter: its name, or <name>_ for an R reserved word.
argument_name <- function(param) if (param %in% reserved_words) paste0(param, "_") else param

# --- Rd text --------------------------------------------------------------------

# Characters past ASCII (the package's Rd files are UTF-8, DESCRIPTION's
# Encoding): an ellipsis is Rd's own \ldots; any other is shown as itself,
# and in the PDF manual (LaTeX has no glyph for every one) as its LaTeX form,
# or as its code point.
latex_forms <- stats::setNames(c("\\eqn{\\cap}", "\\eqn{\\cup}"), c("\u2229", "\u222a"))

rd_non_ascii <- function(text) {
  points <- utf8ToInt(text)
  if (all(points < 128L)) return(text)
  pieces <- intToUtf8(points, multiple = TRUE)
  for (at in which(points >= 128L)) {
    character <- pieces[[at]]
    pieces[[at]] <- if (points[[at]] == 0x2026L) {
      "\\ldots"
    } else {
      latex <- if (character %in% names(latex_forms)) latex_forms[[character]] else sprintf("<U+%04X>", points[[at]])
      paste0("\\ifelse{latex}{", latex, "}{", character, "}")
    }
  }
  paste(pieces, collapse = "")
}

# Escape Rd text: backslash, percent and braces; `code` becomes \code{code}.
rd_text <- function(text) {
  if (is.null(text)) return("")
  text <- gsub("\\", "\\\\", text, fixed = TRUE)
  text <- gsub("%", "\\%", text, fixed = TRUE)
  text <- gsub("{", "\\{", text, fixed = TRUE)
  text <- gsub("}", "\\}", text, fixed = TRUE)
  text <- gsub("`([^`]+)`", "\\\\code{\\1}", text)
  rd_non_ascii(text)
}

rd_code <- function(text) paste0("\\code{", rd_text(text), "}")

# A JSON value as R source: strings quoted, objects as named lists, arrays of
# scalars as c(), other arrays as list(); `cells` adds 1 (an x-cells array is
# given as 1-based positions in R).
r_value <- function(value, schema = NULL) {
  if (is.null(value)) return("NULL")
  if (isTRUE(schema[["x-values"]]) && is.list(value)) {
    numbers <- vapply(value, as.character, "")
    return(if (length(numbers) == 0L) "numeric(0)" else if (length(numbers) == 1L) numbers else paste0("c(", paste(numbers, collapse = ", "), ")"))
  }
  if (isTRUE(schema[["x-cells"]]) && is.list(value)) {
    numbers <- vapply(value, function(cell) cell + 1, 0)
    return(if (length(numbers) == 0L) "integer(0)" else if (length(numbers) == 1L) format(numbers) else paste0("c(", paste(format(numbers), collapse = ", "), ")"))
  }
  if (is.list(value)) {
    keys <- names(value)
    if (!is.null(keys)) {
      if (length(value) == 0L) return("list()")
      properties <- schema$properties
      parts <- vapply(keys, function(key) paste0(r_name(key), " = ", r_value(value[[key]], properties[[key]])), "")
      return(paste0("list(", paste(parts, collapse = ", "), ")"))
    }
    if (length(value) == 0L) return("list()")
    scalars <- all(vapply(value, function(item) !is.list(item) && length(item) == 1L, TRUE))
    items <- vapply(value, r_value, "", schema = schema$items)
    if (scalars && length(items) == 1L) return(items)
    return(paste0(if (scalars) "c(" else "list(", paste(items, collapse = ", "), ")"))
  }
  if (is.character(value)) return(r_string(value))
  if (is.logical(value)) return(if (value) "TRUE" else "FALSE")
  if (is.integer(value)) return(as.character(value))
  deparse(value)
}

r_string <- function(text) {
  text <- gsub("\\", "\\\\", text, fixed = TRUE)
  paste0("\"", gsub("\"", "\\\"", text, fixed = TRUE), "\"")
}

r_name <- function(key) if (make.names(key) == key && !key %in% reserved_words) key else paste0("`", key, "`")

# Rd code escapes (examples, usage): backslash and percent, braces in text.
rd_example <- function(code) {
  code <- gsub("\\", "\\\\", code, fixed = TRUE)
  code <- gsub("%", "\\%", code, fixed = TRUE)
  code <- gsub("{", "\\{", code, fixed = TRUE)
  gsub("}", "\\}", code, fixed = TRUE)
}

# --- Schemas in words -----------------------------------------------------------

# Whether a schema (or one of its forms) is cells: its own description names
# them as the viewer's 0-based positions, which R gives 1-based.
names_cells <- function(schema) {
  isTRUE(schema[["x-cells"]]) || any(vapply(schema$oneOf, names_cells, TRUE))
}

# A schema in words, starting lower case (type_phrase) or upper case
# (describe_type).
describe_type <- function(schema) {
  text <- type_phrase(schema)
  if (startsWith(text, "\\")) text else paste0(toupper(substring(text, 1L, 1L)), substring(text, 2L))
}

type_phrase <- function(schema) {
  if (isTRUE(schema[["x-cells"]])) {
    return(paste0("cells: 1-based positions, \\code{TRUE}/\\code{FALSE} for every cell, or the cell names of the ",
                  "object the viewer shows, each once (sent as original positions)"))
  }
  if (isTRUE(schema[["x-values"]])) {
    return("a column, one value per cell named: numbers (\\code{NA}: no value), or a factor (its codes; \\code{NA}: no category)")
  }
  if (!is.null(schema$const)) return(paste0("exactly ", rd_code(r_value(schema$const))))
  if (!is.null(schema$enum)) {
    return(paste0("one of ", paste(vapply(schema$enum, function(item) rd_code(r_value(item)), ""), collapse = ", ")))
  }
  if (!is.null(schema$oneOf)) {
    forms <- vapply(schema$oneOf, function(form) {
      text <- type_phrase(form)
      if (!is.null(form$description) && !names_cells(form)) {
        text <- paste0(text, " (", sub("\\.$", "", rd_text(form$description)), ")")
      }
      text
    }, "")
    return(paste0("either ", paste(forms, collapse = "; or ")))
  }
  types <- unlist(schema$type)
  words <- vapply(types, function(type) {
    switch(type,
      string = "text",
      integer = "a whole number",
      number = "a number",
      boolean = "\\code{TRUE} or \\code{FALSE}",
      null = "\\code{NULL}",
      array = paste0("a vector or list", if (!is.null(schema$items)) paste0(" of ", type_phrase(schema$items)) else ""),
      object = describe_object(schema)
    )
  }, "")
  text <- paste(words, collapse = " or ")
  bounds <- c(
    if (!is.null(schema$minimum)) paste0("at least ", schema$minimum),
    if (!is.null(schema$exclusiveMinimum)) paste0("more than ", schema$exclusiveMinimum),
    if (!is.null(schema$maximum)) paste0("at most ", schema$maximum),
    if (!is.null(schema$minLength) && schema$minLength > 0) paste0("at least ", schema$minLength, " ", if (schema$minLength == 1) "character" else "characters"),
    if (!is.null(schema$maxLength)) paste0("at most ", schema$maxLength, " characters"),
    if (!is.null(schema$minItems) && schema$minItems > 0) paste0("at least ", schema$minItems, " ", if (schema$minItems == 1) "item" else "items"),
    if (!is.null(schema$maxItems)) paste0("at most ", schema$maxItems, " ", if (schema$maxItems == 1) "item" else "items"),
    if (isTRUE(schema$uniqueItems)) "each once"
  )
  if (length(bounds) > 0L) text <- paste0(text, " (", paste(bounds, collapse = ", "), ")")
  text
}

describe_object <- function(schema) {
  if (length(schema$properties) == 0L) return("an empty named list, \\code{list()}")
  "a named list"
}

# The keys of an object parameter (and of the objects inside it), each with
# its description and type, as an Rd list; "" for a schema with none.
describe_keys <- function(schema) {
  objects <- c(list(schema), schema$oneOf)
  properties <- list()
  required <- character()
  for (form in objects) {
    if (!"object" %in% unlist(form$type) || length(form$properties) == 0L) next
    for (key in names(form$properties)) if (is.null(properties[[key]])) properties[[key]] <- form$properties[[key]]
    required <- union(required, unlist(form$required))
  }
  if (length(properties) == 0L) return("")
  items <- vapply(names(properties), function(key) {
    property <- properties[[key]]
    text <- c(
      if (!is.null(property$description) && !names_cells(property)) sub("\\.?$", ".", rd_text(property$description)),
      paste0(describe_type(property), "."),
      if (key %in% required) "Required." else "Optional.",
      describe_keys(property)
    )
    paste0("\\item{", rd_code(key), "}{", paste(text[nzchar(text)], collapse = " "), "}")
  }, "")
  paste0("\\describe{", paste(items, collapse = ""), "}")
}

# --- One action ---------------------------------------------------------------

# Its parameters: required ones in the order the action names them, then the
# others in the catalog's (alphabetical) order.
ordered_params <- function(action) {
  properties <- action$params$properties
  required <- unlist(action$params$required)
  c(required, setdiff(names(properties), required))
}

# The R default of a parameter: its schema's default when that is a scalar
# (or null), else none (the parameter is left out unless given).
scalar_default <- function(schema) {
  if (!"default" %in% names(schema)) return(NULL)
  value <- schema$default
  if (is.list(value)) return(NULL)
  list(text = r_value(value))
}

formals_text <- function(action) {
  properties <- action$params$properties
  parts <- "viewer"
  for (param in ordered_params(action)) {
    default <- if (param %in% unlist(action$params$required)) NULL else scalar_default(properties[[param]])
    parts <- c(parts, paste0(argument_name(param), if (!is.null(default)) paste0(" = ", default$text) else ""))
  }
  parts
}

function_name <- function(action) paste0("cellucid_", action$tool)

render_function <- function(action) {
  name <- function_name(action)
  required <- unlist(action$params$required)
  params <- ordered_params(action)
  lines <- c(
    paste0("# ", action$type, ": ", action$title),
    paste0(name, " <- function(", paste(formals_text(action), collapse = ", "), ") {")
  )
  for (param in required) {
    lines <- c(lines, paste0("  if (missing(", argument_name(param), ")) .missing_action_param(\"", name, "\", \"",
                             argument_name(param), "\")"))
  }
  if (length(required) > 0L) {
    lines <- c(lines, paste0("  params <- list(", paste0(
      vapply(required, function(param) paste0(r_name(param), " = ", argument_name(param)), ""), collapse = ", "), ")"))
  } else {
    lines <- c(lines, "  params <- list()")
  }
  for (param in setdiff(params, required)) {
    lines <- c(lines, paste0("  if (!missing(", argument_name(param), ")) params[\"", param, "\"] <- list(",
                             argument_name(param), ")"))
  }
  c(lines, paste0("  .act(viewer, \"", action$type, "\", params, \"", name, "()\")"), "}")
}

# A usage block within 90 characters a line, as R CMD check asks.
usage_text <- function(action) {
  arguments <- formals_text(action)
  one <- paste0(function_name(action), "(", paste(arguments, collapse = ", "), ")")
  if (nchar(one) <= 90L) return(rd_example(one))
  rd_example(c(paste0(function_name(action), "("), paste0("  ", arguments, c(rep(",", length(arguments) - 1L), "")), ")"))
}

# An example call, its parameters the catalog's example, laid out by R's
# deparser within 80 characters a line.
example_call <- function(action) {
  example <- action$example
  properties <- action$params$properties
  values <- vapply(names(example), function(key) {
    paste0(argument_name(key), " = ", r_value(example[[key]], properties[[key]]))
  }, "")
  call <- parse(text = paste0("request <- ", function_name(action), "(", paste(c("viewer", values), collapse = ", "), ")"))[[1L]]
  sub(" +$", "", paste0("  ", deparse(call, width.cutoff = 50L)))
}

render_rd <- function(action) {
  name <- function_name(action)
  properties <- action$params$properties
  required <- unlist(action$params$required)
  items <- "\\item{viewer}{A viewer \\code{\\link{cellucid_view}()} or \\code{\\link{cellucid_serve}()} returned.}"
  for (param in ordered_params(action)) {
    schema <- properties[[param]]
    text <- c(
      if (!is.null(schema$description) && !names_cells(schema)) sub("\\.?$", ".", rd_text(schema$description)),
      paste0(describe_type(schema), "."),
      if (param %in% required) {
        "Required."
      } else if (!is.null(scalar_default(schema))) {
        paste0("Default ", rd_code(scalar_default(schema)$text), ", the viewer's own.")
      } else {
        "Left out unless given (the viewer then chooses as its own control does)."
      },
      if (!identical(argument_name(param), param)) paste0("Sent as the parameter ", rd_code(param), "."),
      describe_keys(schema)
    )
    text <- text[nzchar(text)]
    items <- c(items, paste0("\\item{", argument_name(param), "}{", paste(text, collapse = " "), "}"))
  }
  read <- identical(action$effect, "read")
  # A read, a stop of work under way, a move of the history (undo, redo, a jump), another dataset
  # opened, or an act outside the state and history (a file, a publication, what the browser
  # keeps): no step.
  stepless <- read || action$effect %in% c("control", "history", "dataset", "outside")
  returned <- if (read) "what it read" else "its outcome"
  value <- c(
    "A \\code{cellucid_action_request}, at once and invisibly: the action is sent now, or when the viewer's channel opens.",
    if (stepless && length(action$result$properties) == 0L) {
      paste0("\\code{\\link{cellucid_action_result}(request)} returns ", returned, ".")
    } else if (stepless) {
      fields <- names(action$result$properties)
      paste0("\\code{\\link{cellucid_action_result}(request)} returns ", returned, ": a list of ",
             paste(vapply(fields, function(field) {
               description <- action$result$properties[[field]]$description
               paste0(rd_code(field), if (!is.null(description)) paste0(" (", sub("\\.$", "", rd_text(description)), ")") else "")
             }, ""), collapse = ", "),
             if (read) ". Cells in it are original positions (0-based rows of the dataset's obs)." else ".")
    } else {
      paste0("\\code{\\link{cellucid_action_result}(request)} returns its outcome (what it did, as names, counts and ids), ",
             "or \\code{NULL} when it had nothing to report; \\code{request$step} is the history step it made.")
    }
  )
  effect <- switch(action$effect,
    state = "It changes the viewer's state",
    view = "It changes what the viewer shows",
    layout = "It changes the viewer's layout",
    read = "It reads, and changes nothing",
    control = "It stops work under way in the viewer at once, also while the request that started it is still waiting; that work's own step records what it changed",
    history = "It moves the viewer's history, as the person's Undo, Redo or a click on a step does",
    dataset = "It opens another dataset in place of the one the viewer shows, as an agent in the viewer does",
    outside = "It acts outside the viewer's state and history (a file the person receives in the browser, a publication, or what the browser keeps for later visits), which Undo does not take back",
    stop("The action ", action$type, " has the effect ", action$effect, ", which this generator does not know.")
  )
  details <- c(
    paste0("The viewer's action ", rd_code(action$type), " (", rd_text(action$group), "). ", effect,
           if (stepless) ": it makes no step of the history." else
             ": one step of the viewer's history, labeled as R's, undone like any other.",
           if (length(action$touches) > 0L) paste0(" The state it can change: ",
                                                   paste(vapply(unlist(action$touches), rd_code, ""), collapse = ", "), ".") else ""),
    if (identical(action$effect, "dataset")) paste0("A viewer opened from R shows the dataset R serves, so the viewer refuses this ",
                                                    "action from R: show another dataset with \\code{\\link{cellucid_view}}."),
    if (identical(action$confirm, "publishes")) paste0("It publishes for others to see, so the viewer asks the person first (publishes), ",
                                                       "from R too, as when an agent (Claude, ChatGPT) runs it; ",
                                                       "\\code{\\link{cellucid_action_result}(request)} waits for their answer (call it again if its timeout passes first)."),
    if (!is.null(action$confirm) && !identical(action$confirm, "publishes")) paste0("When an agent (Claude, ChatGPT) runs it, the viewer asks the person first (",
                                         rd_text(action$confirm), "); from R it is not asked.")
  )
  c(
    paste0("% ", generated_header),
    paste0("\\name{", name, "}"),
    paste0("\\alias{", name, "}"),
    paste0("\\title{", rd_text(action$title), "}"),
    "\\usage{",
    usage_text(action),
    "}",
    "\\arguments{",
    items,
    "}",
    "\\value{",
    value,
    "}",
    "\\description{",
    rd_text(action$summary),
    "}",
    "\\details{",
    # One line per element, a blank line between paragraphs: the page is
    # compared line by line with what is on disk.
    head(as.vector(rbind(details, "")), -1L),
    "}",
    "\\seealso{",
    "\\code{\\link{cellucid_act}()} sends any action by its type, and \\code{\\link{cellucid_action_result}()}",
    "collects its answer.",
    "}",
    "\\examples{",
    "if (interactive() && requireNamespace(\"SeuratObject\", quietly = TRUE)) {",
    "  data(\"pbmc_small\", package = \"SeuratObject\")",
    "  viewer <- cellucid_view(SeuratObject::UpdateSeuratObject(pbmc_small))",
    rd_example(example_call(action)),
    "  print(request)",
    if (read) "  # cellucid_action_result(request) waits for what it read." else
      "  # cellucid_action_result(request) waits for its outcome.",
    "  cellucid_stop(viewer)",
    "}",
    "}"
  )
}

# --- The whole set ----------------------------------------------------------------

read_catalog <- function(root) {
  jsonlite::read_json(file.path(root, "inst", "action_catalog.json"), simplifyVector = FALSE)
}

# The hand-written exports of NAMESPACE: every export( outside the generated
# block.
hand_written_exports <- function(namespace) {
  inside <- cumsum(namespace == namespace_begin) - cumsum(namespace == namespace_end) > 0L | namespace == namespace_end
  lines <- namespace[!inside]
  sub("^export\\((.*)\\)$", "\\1", grep("^export\\(", lines, value = TRUE))
}

# Every generated file, rendered: a named list, path relative to `root` ->
# its lines.
render_actions <- function(root) {
  catalog <- read_catalog(root)
  if (!identical(catalog$schema, 1L)) stop("inst/action_catalog.json is of schema ", catalog$schema, "; this generator reads schema 1.")
  actions <- catalog$actions
  names <- vapply(actions, function_name, "")
  if (anyDuplicated(names)) stop("Two actions have the tool name ", names[anyDuplicated(names)], ".")
  namespace <- readLines(file.path(root, "NAMESPACE"), warn = FALSE, encoding = "UTF-8")
  taken <- intersect(names, hand_written_exports(namespace))
  if (length(taken) > 0L) stop("A generated function takes a hand-written export's name: ", paste(taken, collapse = ", "), ".")
  for (action in actions) {
    for (param in names(action$params$properties)) {
      argument <- argument_name(param)
      if (make.names(argument) != argument || argument %in% c("viewer", "params")) {
        stop("The parameter ", param, " of ", action$type, " has no R argument name.")
      }
    }
  }
  code <- c(paste0("# ", generated_header), "")
  for (action in actions) code <- c(code, render_function(action), "")
  files <- list(`R/actions-generated.R` = code[-length(code)])
  for (action in actions) {
    page <- render_rd(action)
    # R CMD check notes \usage lines past 90 characters and \examples
    # lines past 100: a catalog that would make one fails here instead.
    usage <- page[seq(which(page == "\\usage{") + 1L, which(page == "\\arguments{") - 2L)]
    examples <- page[seq(which(page == "\\examples{"), length(page))]
    if (any(nchar(usage, type = "width") > 90L) || any(nchar(examples, type = "width") > 100L)) {
      stop("The help page of ", action$type, " has a usage line past 90 characters or an example line past 100.")
    }
    files[[file.path("man", paste0(function_name(action), ".Rd"))]] <- page
  }
  begin <- which(namespace == namespace_begin)
  end <- which(namespace == namespace_end)
  if (length(begin) != 1L || length(end) != 1L || end < begin) {
    stop("NAMESPACE must hold one block between \"", namespace_begin, "\" and \"", namespace_end, "\".")
  }
  files$NAMESPACE <- c(namespace[seq_len(begin)], paste0("export(", sort(names, method = "radix"), ")"),
                       namespace[end:length(namespace)])
  files$`_pkgdown.yml` <- render_pkgdown(root, names)
  files
}

# _pkgdown.yml with its reference group of the actions' pages listing exactly
# the generated functions (a hand-kept list kept two removed pages and missed
# a new one, failing the site's build: CI run 43106603397).
render_pkgdown <- function(root, names) {
  site <- readLines(file.path(root, "_pkgdown.yml"), warn = FALSE, encoding = "UTF-8")
  title <- which(site == pkgdown_actions_title)
  if (length(title) != 1L || !identical(site[title + 1L], "    contents:")) {
    stop("_pkgdown.yml must hold one reference group \"", pkgdown_actions_title, "\" with its contents.")
  }
  first <- title + 2L
  last <- first - 1L
  while (last < length(site) && startsWith(site[[last + 1L]], "      - ")) last <- last + 1L
  c(site[seq_len(first - 1L)], paste0("      - ", sort(names, method = "radix")), site[-seq_len(last)])
}

# The generated help pages on disk that no action renders any more.
stale_pages <- function(root, files) {
  pages <- list.files(file.path(root, "man"), pattern = "\\.Rd$")
  generated <- pages[vapply(pages, function(page) {
    identical(readLines(file.path(root, "man", page), n = 1L, warn = FALSE, encoding = "UTF-8"), generated_rd_marker)
  }, TRUE)]
  setdiff(file.path("man", generated), names(files))
}

write_actions <- function(root = ".") {
  files <- render_actions(root)
  for (path in stale_pages(root, files)) file.remove(file.path(root, path))
  for (path in names(files)) {
    connection <- file(file.path(root, path), "wb")
    writeLines(enc2utf8(files[[path]]), connection, sep = "\n", useBytes = TRUE)
    close(connection)
  }
  invisible(names(files))
}

if (sys.nframe() == 0L) {
  written <- write_actions(".")
  cat("Wrote", length(written), "files from inst/action_catalog.json.\n")
}
