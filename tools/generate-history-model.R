# Writes R/history-model-generated.R from inst/history_model.schema.json, the
# web app's history model (app/history/model.js historyModelDocument), byte
# for byte the file cellucid-python and the web app hold (its home is the web
# repository's tests/fixtures/history-model.schema.json, which
# tests/testthat/test-history-model.R compares it with): every record a
# history, a saved state and a session file hold -- trackers, branches, steps,
# notes, turns, the journal, the apply plan and its report -- with each
# field's key, its name in R (snake case: headId is head_id; Python's names,
# but `from`, which R allows), its type and whether it may be left out; the
# model's constants and enumerations. The session reader checks every record
# against these fields, and the reading model exposes every one of them:
# nothing about a record is written by hand.
#
# Run from the package root after the model changes:
#
#   Rscript tools/generate-history-model.R
#
# tests/testthat/test-history-model.R renders the same file in memory
# (render_history_model()) and fails while the file on disk differs. Needs
# jsonlite only, never the package itself.

history_model_header <- c(
  "Generated by tools/generate-history-model.R from inst/history_model.schema.json:",
  "do not edit. Run `Rscript tools/generate-history-model.R` from the package root",
  "after the model changes; tests/testthat/test-history-model.R fails while this",
  "file is stale."
)

# Records read as maps of their keys (domain ids), not as records of fields.
history_map_records <- c("DomainValues", "Reads")

# The model's enumerations, by the field that names them.
history_enums <- list(
  BY_ORIGINS = c("By", "origin"),
  HISTORY_HOSTS = c("By", "host"),
  STEP_STATUSES = c("Step", "status"),
  STEP_KINDS = c("Step", "kind"),
  SQUASH_CAUSES = c("Squash", "cause"),
  TRACKER_START_KINDS = c("Start", "kind"),
  REPLAY_OUTCOMES = c("ReplayEntry", "outcome"),
  SHARE_CONTENTS = c("Scope", "content"),
  SHARE_RESULTS = c("Scope", "results"),
  SHARE_TIMES = c("Scope", "times"),
  SHARE_SOURCES = c("Scope", "source"),
  APPLY_ROW_KINDS = c("ApplyPlanRow", "kind"),
  APPLY_ROW_STATUSES = c("ApplyPlanRow", "status"),
  APPLY_PACKAGES = c("Provenance", "package")
)

snake_name <- function(key) {
  gsub("([a-z0-9])([A-Z])", "\\1_\\L\\2", key, perl = TRUE)
}

# A field's spec, as the model writes it (model.js specSchema read back).
history_spec <- function(schema, hash_pattern) {
  if (!is.null(schema$anyOf)) {
    return(list(type = "record", name = sub(".*/", "", schema$anyOf[[1L]]$`$ref`), nullable = TRUE))
  }
  if (!is.null(schema$`$ref`)) return(list(type = "record", name = sub(".*/", "", schema$`$ref`), nullable = FALSE))
  if (!is.null(schema$enum)) {
    values <- schema$enum
    nullable <- any(vapply(values, is.null, TRUE))
    return(list(type = "enum", values = unlist(Filter(Negate(is.null), values)), nullable = nullable))
  }
  if (!is.null(schema$`x-time`)) return(list(type = "time", nullable = TRUE))
  types <- unlist(schema$type)
  nullable <- "null" %in% types
  types <- setdiff(types, "null")
  if (length(types) == 0L) return(list(type = "json", nullable = TRUE))
  kind <- types[[1L]]
  if (identical(kind, "string")) {
    if (!is.null(schema$`x-id`)) return(list(type = "id", kind = schema$`x-id`, nullable = nullable))
    if (isTRUE(schema$`x-name`)) return(list(type = "name", nullable = nullable))
    if (identical(schema$pattern, hash_pattern)) return(list(type = "hash", nullable = nullable))
    if (!is.null(schema$pattern)) return(list(type = "string", pattern = schema$pattern, nullable = nullable))
    if (identical(schema$minLength, 1L)) return(list(type = "text", nullable = nullable))
    return(list(type = "string", pattern = NULL, nullable = nullable))
  }
  if (identical(kind, "boolean")) return(list(type = "boolean", nullable = nullable))
  if (identical(kind, "integer")) {
    return(list(type = "integer", minimum = schema$minimum, maximum = schema$maximum, nullable = nullable))
  }
  if (identical(kind, "number")) return(list(type = "number", minimum = schema$minimum, nullable = nullable))
  if (identical(kind, "object")) return(list(type = "object", nullable = nullable))
  if (identical(kind, "array")) {
    if (!is.null(schema$prefixItems)) {
      return(list(type = "pair", items = lapply(schema$prefixItems, history_spec, hash_pattern = hash_pattern), nullable = nullable))
    }
    return(list(type = "array", item = history_spec(schema$items, hash_pattern), nullable = nullable))
  }
  stop("Unread spec: ", jsonlite::toJSON(schema, auto_unbox = TRUE))
}

r_literal <- function(value) paste(deparse(value, width.cutoff = 500L, control = c("keepNA", "keepInteger", "niceNames", "showAttributes")), collapse = "\n")

render_history_model <- function(root = ".") {
  path <- file.path(root, "inst", "history_model.schema.json")
  text <- readChar(path, file.size(path), useBytes = TRUE)
  schema <- jsonlite::parse_json(text, simplifyVector = FALSE)
  hash_pattern <- schema$`$defs`$AppStamp$properties$catalog$pattern
  fields <- list()
  for (name in names(schema$`$defs`)) {
    definition <- schema$`$defs`[[name]]
    required <- unlist(definition$required)
    order <- c(required, sort(setdiff(names(definition$properties), required), method = "radix"))
    fields[[name]] <- lapply(order, function(key) {
      list(key = key, attr = snake_name(key), spec = history_spec(definition$properties[[key]], hash_pattern),
           optional = !key %in% required)
    })
  }
  enums <- lapply(history_enums, function(path) {
    field <- Filter(function(entry) identical(entry$key, path[[2L]]), fields[[path[[1L]]]])[[1L]]
    field$spec$values
  })
  constants <- schema$`x-constants`
  white <- vapply(schema$`x-names`$whiteSpace, function(code) strtoi(sub("U\\+", "", code), 16L), 0L)
  lines <- c(
    paste("#", history_model_header),
    "",
    paste0(".history_model_version <- ", schema$version, "L"),
    "# Id forms (HISTORY_ID_PATTERNS) and a value's content hash.",
    paste0(".history_id_patterns <- ", r_literal(unlist(schema$`x-ids`))),
    paste0(".history_value_hash_pattern <- ", r_literal(hash_pattern)),
    paste0(".history_root_step <- ", r_literal(constants$rootStep)),
    paste0(".history_first_branch <- ", r_literal(constants$firstBranch)),
    paste0(".history_first_branch_name <- ", r_literal(constants$firstBranchName)),
    paste0(".history_lane_count <- ", constants$laneCount, "L"),
    paste0(".history_outside_change_type <- ", r_literal(constants$outsideChangeType)),
    paste0(".history_fresh_start_branch_name <- ", r_literal(constants$freshStartBranchName)),
    paste0(".history_root_labels <- ", r_literal(unlist(constants$rootLabels))),
    "# White space in a name, as code points: trimmed from both ends, each inner run one space.",
    paste0(".history_name_white_space <- ", r_literal(as.integer(white))),
    "# The state domains, in the order a full restore applies them.",
    paste0(".history_domains <- ", r_literal(unlist(schema$`x-domains`))),
    paste0(".history_read_inputs <- ", r_literal(unlist(schema$`x-readInputs`))),
    paste0(".history_journal_ops <- ", r_literal(unlist(schema$`x-journalOps`))),
    paste0(".history_tracker_patch_fields <- ", r_literal(unlist(schema$`x-trackerPatchFields`))),
    "# The model's enumerations.",
    paste0(".history_enums <- ", r_literal(enums)),
    "# The records read as maps of domain ids ({domain: value hash}), not as records of fields.",
    paste0(".history_map_records <- ", r_literal(history_map_records)),
    "# Every record's fields in the model's order: key, its name in R, its spec, whether it may be left out.",
    paste0(".history_fields <- ", r_literal(fields)),
    "# What each record is, in the model's words.",
    paste0(".history_descriptions <- ", r_literal(vapply(schema$`$defs`, function(definition) definition$description, ""))),
    ""
  )
  paste(lines, collapse = "\n")
}

if (sys.nframe() == 0L) {
  arguments <- commandArgs(trailingOnly = TRUE)
  check <- "--check" %in% arguments
  text <- render_history_model(".")
  target <- file.path("R", "history-model-generated.R")
  current <- if (file.exists(target)) readChar(target, file.size(target), useBytes = TRUE) else ""
  if (identical(current, text)) {
    cat("current ", target, "\n", sep = "")
  } else if (check) {
    cat("stale   ", target, ": run Rscript tools/generate-history-model.R\n", sep = "")
    quit(status = 1L)
  } else {
    writeBin(charToRaw(text), target)
    cat("wrote   ", target, "\n", sep = "")
  }
}
