# The Cellucid citation is written once, in the preferred-citation block that
# every Cellucid repository's CITATION.cff shares, and generated everywhere
# else by cellucid-private/scripts/sync_citation.py. Each generated region
# records the SHA-256 of the block it came from and of its own body, so a block
# changed without re-running the script, or a region edited by hand, fails here.
#
# inst/CITATION and README.md ship in the package; CITATION.cff does not, so the
# comparison with the block runs in a source checkout only. The digests come from
# the package's own SHA-256, so both checks run on every supported R.

cellucid_text_bytes <- function(path) {
  bytes <- readBin(path, "raw", file.info(path)$size)
  text <- rawToChar(bytes)
  Encoding(text) <- "UTF-8"
  text
}

cellucid_sha256_text <- function(text) {
  cellucid:::.native_sha256(charToRaw(enc2utf8(text)))
}

cellucid_citation_region <- function(text, comment_open, comment_close) {
  begin_pattern <- paste0(
    "(^|\n)", comment_open,
    "BEGIN cellucid-citation \\(generated by ",
    "cellucid-private/scripts/sync_citation\\.py from CITATION\\.cff; ",
    "do not edit\\) source-sha256=([0-9a-f]{64}) ",
    "body-sha256=([0-9a-f]{64})", comment_close, "\n"
  )
  end_line <- paste0(comment_open, "END cellucid-citation", comment_close, "\n")
  begins <- gregexpr(begin_pattern, text, perl = TRUE)[[1L]]
  expect_identical(length(begins[begins > 0L]), 1L)
  ends <- gregexpr(end_line, text, fixed = TRUE)[[1L]]
  expect_identical(length(ends[ends > 0L]), 1L)
  match <- regmatches(text, regexec(begin_pattern, text, perl = TRUE))[[1L]]
  body_start <- begins[[1L]] + attr(begins, "match.length")[[1L]]
  list(
    source = match[[3L]],
    recorded_body = match[[4L]],
    body = substr(text, body_start, ends[[1L]] - 1L)
  )
}

cellucid_citation_block <- function(path) {
  lines <- strsplit(cellucid_text_bytes(path), "(?<=\n)", perl = TRUE)[[1L]]
  stripped <- sub("\n$", "", lines)
  begin <- which(stripped == "# BEGIN cellucid preferred-citation")
  end <- which(stripped == "# END cellucid preferred-citation")
  expect_identical(length(begin), 1L)
  expect_identical(length(end), 1L)
  block <- paste(lines[begin:end], collapse = "")
  if (!endsWith(block, "\n")) block <- paste0(block, "\n")
  block
}

cellucid_generated_citations <- function() {
  root <- cellucid_repository_root()
  list(
    list(path = file.path(root, "inst", "CITATION"), open = "# ", close = ""),
    list(path = file.path(root, "README.md"), open = "<!-- ", close = " -->")
  )
}

test_that("generated citations were not edited by hand", {
  for (surface in cellucid_generated_citations()) {
    region <- cellucid_citation_region(
      cellucid_text_bytes(surface$path), surface$open, surface$close
    )
    expect_identical(
      region$recorded_body,
      cellucid_sha256_text(region$body),
      info = paste(
        surface$path,
        "was edited by hand; edit theislab/cellucid/CITATION.cff and run",
        "cellucid-private/scripts/sync_citation.py"
      )
    )
  }
})

test_that("generated citations match this checkout's CITATION.cff", {
  skip_if_not(cellucid_is_source_checkout(), "CITATION.cff is not shipped")
  block <- cellucid_citation_block(
    file.path(cellucid_repository_root(), "CITATION.cff")
  )
  placeholder <- !grepl("(^|\n)  doi:", block)
  for (surface in cellucid_generated_citations()) {
    region <- cellucid_citation_region(
      cellucid_text_bytes(surface$path), surface$open, surface$close
    )
    expect_identical(
      region$source,
      cellucid_sha256_text(block),
      info = paste(
        "CITATION.cff changed after", surface$path, "was generated; run",
        "cellucid-private/scripts/sync_citation.py"
      )
    )
    expect_identical(grepl("Placeholder citation", region$body), placeholder)
  }
})

test_that("citation() lists the Cellucid preprint first, then the package", {
  entries <- utils::readCitationFile(
    file.path(cellucid_repository_root(), "inst", "CITATION"),
    meta = list(Version = cellucid_description_version(), Encoding = "UTF-8")
  )
  expect_length(entries, 2L)
  records <- unclass(entries)
  expect_identical(attr(records[[1L]], "key"), "cellucid")
  expect_identical(attr(records[[2L]], "bibtype"), "Manual")
  preprint <- format(entries[1L], style = "text")
  expect_match(preprint, "Inecik", fixed = TRUE)
})
